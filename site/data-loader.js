/* Pick n Edge data loader. The site reads ready files from site/data; it never calls the EuroLeague APIs and holds no formulas.
   Open: manifest, metrics, roster, schedule and the Season views. Everything else (other windows, per-game rows, shots, the
   metric engine) is loaded on demand. Metric values come from the views; custom windows (Last 7, home/away...) are summed from
   per-game rows by the SAME engine the tests cover (data/engine/*.mjs, generated by the build).

   Cell encoding in views: null (no value) | number | [value, gamesUsed, gamesPlayed] (partial coverage).
   get() returns {value, used, of} with used/of = null when every game counted.                                                  */
(function (root, factory) {
  const api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else { api.script = (typeof document !== 'undefined' && document.currentScript && document.currentScript.src) || ''; root.PicknEdgeData = api.create({ base: api.script ? new URL('data/', api.script).href : 'data/' }); root.PicknEdgeDataFactory = api; }
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {

  const OLD_CACHE = /^(picknedge-schedule-|picknedge-shots-|courtvision-betting-(live|people)-)/;   // keys of the old browser-side data cache
  const decode = c => c === null || c === undefined ? { value: null, used: null, of: null } : Array.isArray(c) ? { value: c[0], used: c[1], of: c[2] } : { value: c, used: null, of: null };

  function create({ base, fetch: fetchFn, importer, storage } = {}) {
    const doFetch = fetchFn || ((u, o) => fetch(u, o));
    const doImport = importer || (u => import(u));
    const cache = new Map();
    let version = '';
    const once = (key, fn) => { if (!cache.has(key)) cache.set(key, fn().catch(e => { cache.delete(key); throw e; })); return cache.get(key); };
    const url = path => base + path + (version ? '?v=' + version : '');
    const json = path => once(path, async () => {
      const res = await doFetch(url(path), path === 'manifest.json' ? { cache: 'no-cache' } : {});
      if (!res.ok) throw new Error(`Could not load ${path} (HTTP ${res.status})`);
      return res.json();
    });

    const manifest = () => once('manifest', async () => { const m = await json('manifest.json'); version = m.version; return m; });
    const need = async path => { await manifest(); return json(path); };

    /* ---- views ---- */
    function makeView(kind, window, data, ids) {
      const index = Object.fromEntries(data.metrics.map((id, i) => [id, i]));
      const cellOf = (row, id) => (id in index && row ? row[index[id]] : undefined);
      return {
        kind, window, metrics: data.metrics, keys: Object.keys(data.rows),
        row: key => data.rows[key] || null,
        get: (key, id) => { const r = data.rows[key]; return r && id in index ? decode(r.v[index[id]]) : null; },
        league: id => (id in index && data.league ? decode(data.league[index[id]]) : null),
        leagueOf: (k, id) => (id in index && data.leagues?.[k] ? decode(data.leagues[k][index[id]]) : null),
      };
    }
    const view = (kind, window) => once(`view:${kind}:${window}`, async () => makeView(kind, window, await need(`${kind}-${window}.json`)));

    /* ---- per-game rows ---- */
    function records(table) {
      return table.rows.map(r => Object.fromEntries(table.columns.map((c, i) => [c, r[i]])));
    }
    const games = kind => once(`games:${kind}`, async () => records(await need(`games/${kind}.json`)));
    const shots = team => once(`shots:${team}`, async () => records(await need(`shots/${team}.json`)));

    /* ---- engine (the tested modules) ---- */
    const engine = () => once('engine', async () => {
      await manifest();
      const [eng, reg, join, zones] = await Promise.all(['engine.mjs', 'registry.mjs', 'join.mjs', 'zones.mjs'].map(f => doImport(url('engine/' + f))));
      return { evaluate: eng.evaluate, evaluateAll: eng.evaluateAll, termValue: eng.termValue, byId: eng.byId, METRICS: reg.METRICS, DERIVED: reg.DERIVED, withOpponent: join.withOpponent, zones };
    });

    /* Custom window. spec = { last: N | Infinity, venue: 'all' | 'home' | 'away' }: each team's games are filtered by venue, then
       its last N are taken; a player's sample is his appearances in those games of his current team. */
    const encode = res => res.value === null ? null : res.used === res.of ? res.value : [res.value, res.used, res.of];
    const order = (a, b) => a.date_utc.localeCompare(b.date_utc) || a.game - b.game;
    async function windowRows(kind, spec = {}) {
      const { last = Infinity, venue = 'all' } = spec;
      const [eng, teamRows] = await Promise.all([engine(), games('teams')]);
      const ok = r => venue === 'all' || (venue === 'home') === (r.home === 1);
      const picked = {};                                              // team -> rows (opponent figures joined) of its selected games, oldest first
      for (const r of eng.withOpponent(teamRows).filter(ok).sort(order)) (picked[r.team] ||= []).push(r);
      for (const t of Object.keys(picked)) picked[t] = picked[t].slice(-last);
      if (kind === 'teams') return { eng, ms: eng.METRICS.filter(m => m.scope === 'team' && !m.internal), rows: picked, info: Object.fromEntries(Object.entries(picked).map(([t, rs]) => [t, { games: rs.length }])) };
      const ms = eng.METRICS.filter(m => m.scope === 'player' && !m.internal), roster = (await need('roster.json')).players, byPlayer = {};
      for (const r of [...(await games('players'))].sort(order)) (byPlayer[r.player_id] ||= []).push(r);
      const rows = {}, info = {};
      for (const [pid, list] of Object.entries(byPlayer)) {
        const team = list.at(-1).team, set = new Set((picked[team] || []).map(r => r.game));
        rows[pid] = list.filter(r => r.team === team && set.has(r.game));
        info[pid] = { team, name: roster[pid]?.name || pid, pos: roster[pid]?.pos || '' };
      }
      return { eng, ms, rows, info };
    }
    async function customView(kind, spec = {}) {
      const { eng, ms, rows, info } = await windowRows(kind, spec), out = {}, all = [];
      for (const rs of Object.values(rows)) all.push(...rs);
      for (const [key, rs] of Object.entries(rows)) { const res = eng.evaluateAll(ms, rs, all); out[key] = { ...info[key], v: ms.map(m => encode(res[m.id])) }; }
      const lg = eng.evaluateAll(ms, all, all);                              // metrics compared with the league use the league of this window
      return makeView(kind, 'custom', { metrics: ms.map(m => m.id), league: ms.map(m => encode(lg[m.id])), rows: out });
    }
    /* The games (codes) a team's window covers: venue filter first, then the last N. */
    async function windowGames(team, spec = {}) {
      const { last = Infinity, venue = 'all' } = spec, rows = (await games('teams')).filter(r => r.team === team && (venue === 'all' || (venue === 'home') === (r.home === 1))).sort(order);
      return new Set(rows.slice(-last).map(r => r.game));
    }
    /* Value of every metric over a chosen set of rows of a window (e.g. the league average of the players left by the page filters). */
    async function average(kind, spec, keys) {
      const { eng, ms, rows } = await windowRows(kind, spec), all = keys.flatMap(k => rows[k] || []);
      return makeView(kind, 'average', { metrics: ms.map(m => m.id), league: ms.map(m => encode(eng.evaluate(m, all))), rows: {} });
    }

    /* Analysis helpers served with the engine (the Venn): loaded on first use. */
    const analysis = name => once('analysis:' + name, async () => { await manifest(); return doImport(url('engine/' + name + '.mjs')); });

    /* ---- small things ---- */
    const metrics = () => once('metrics', async () => { const list = await need('metrics.json'); return { list, byId: Object.fromEntries(list.map(m => [m.id, m])) }; });
    const roster = () => need('roster.json');
    const schedule = () => need('schedule.json');
    const status = async () => { const m = await manifest(); return `${m.games} games · latest ${String(m.lastDate).slice(0, 10)}`; };
    /* The old site cached EuroLeague data in localStorage; drop those keys once. */
    function clearOldCaches(store = storage || (typeof localStorage !== 'undefined' ? localStorage : null)) {
      if (!store) return 0;
      let n = 0;
      try { for (const k of Object.keys(store)) if (OLD_CACHE.test(k)) { store.removeItem(k); n++; } } catch { /* storage unavailable */ }
      return n;
    }

    return { manifest, metrics, view, customView, average, windowGames, analysis, games, shots, roster, schedule, engine, status, clearOldCaches, records, decode };
  }
  return { create, decode };
});
