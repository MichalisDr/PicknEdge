// data/clean -> Season / L3 / L5 / L10 views, metrics.json and docs/METRICS.md.
// Usage: node scripts/build/views.mjs [--out .build-tmp/views]   (site/data is NOT written until we decide to)
// Window = the team's last N games; a player's window is his rows in his current team's last N games.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from './csv.mjs';
import { METRICS, DERIVED } from '../metrics/registry.mjs';
import { evaluate } from '../metrics/engine.mjs';
import { withOpponent } from '../metrics/join.mjs';

const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i > 0 ? process.argv[i + 1] : d; };
const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(repo, arg('out', '.build-tmp/views'));
const read = f => parseCsv(readFileSync(join(repo, 'data', 'clean', f), 'utf8'));

export const WINDOWS = { season: Infinity, l3: 3, l5: 5, l10: 10 };
const PLAYER_METRICS = METRICS.filter(m => m.scope === 'player'), TEAM_METRICS = METRICS.filter(m => m.scope === 'team');
const byGame = (a, b) => a.date_utc.localeCompare(b.date_utc) || a.game - b.game;
const roundedCell = r => r.value === null ? null : r.used === r.of ? +r.value.toFixed(6) : [+r.value.toFixed(6), r.used, r.of];   // [value, used, of] when coverage is partial

export function buildViews({ players, teams, dim }, { precise = false } = {}) {
  const cell = precise ? r => r : roundedCell;                         // precise = full-precision {value, used, of} (parity gate)
  const teamRows = withOpponent(teams);
  const gamesOf = {};                                                 // team -> games, oldest first
  for (const r of [...teams].sort(byGame)) (gamesOf[r.team] ||= []).push(r.game);
  const lastN = (team, n) => new Set(gamesOf[team].slice(-n));
  const byPlayer = {};
  for (const r of [...players].sort(byGame)) (byPlayer[r.player_id] ||= []).push(r);
  const info = Object.fromEntries(dim.map(d => [d.player_id, d]));
  const views = {};
  for (const [w, n] of Object.entries(WINDOWS)) {
    const prows = {};
    for (const [pid, list] of Object.entries(byPlayer)) {
      const team = list.at(-1).team, set = lastN(team, n);
      const rows = list.filter(r => r.team === team && set.has(r.game));
      if (!rows.some(r => r.played)) continue;                        // no appearance in the window
      prows[pid] = { team, name: list.at(-1).player, pos: info[pid]?.position || '', v: PLAYER_METRICS.map(m => cell(evaluate(m, rows))) };
    }
    const trows = {};
    for (const team of Object.keys(gamesOf)) {
      const set = lastN(team, n);
      trows[team] = { games: set.size, v: TEAM_METRICS.map(m => cell(evaluate(m, teamRows.filter(r => r.team === team && set.has(r.game))))) };
    }
    views[w] = {
      players: { window: w, metrics: PLAYER_METRICS.map(m => m.id), rows: prows },
      teams: { window: w, metrics: TEAM_METRICS.map(m => m.id), rows: trows },
    };
  }
  return views;
}

/* ---------- generated metric catalog ---------- */
const termText = terms => terms.map(([c, n], i) => `${i ? (c < 0 ? ' − ' : ' + ') : (c < 0 ? '−' : '')}${Math.abs(c) === 1 ? '' : Math.abs(c) + '·'}${n}`).join('');
const formulaOf = m => {
  if (m.kind === 'custom') return `custom function of the window's summed ${m.needs.join(', ')}`;
  const num = termText(m.num), den = m.kind === 'perMin' ? 'sec' : m.kind === 'count' ? '' : termText(m.den);
  const mult = m.mult ?? { per100: 100, pct: 100, perMin: 60, perGame: 1, ratio: 1, count: 1 }[m.kind];
  if (m.kind === 'count') return `Σ ${num}`;
  const body = `Σ(${num}) ÷ Σ(${den})`;
  return mult === 1 ? body : `${mult} × ${body}`;
};
export const catalog = () => METRICS.map(m => ({
  id: m.id, label: m.label, scope: m.scope, kind: m.kind, tags: m.tags, description: m.description,
  format: { digits: m.digits, suffix: m.kind === 'pct' ? '%' : '' },
}));
export function docsMarkdown() {
  const section = (title, scope) => [`## ${title}`, '', '| id | Metric | Kind | Formula | Used in | Description |', '|---|---|---|---|---|---|',
    ...METRICS.filter(m => m.scope === scope).map(m => `| \`${m.id}\` | ${m.label} | ${m.kind} | ${formulaOf(m)} | ${m.tags.join(', ')} | ${m.description} |`), ''];
  return ['<!-- Generated by scripts/build/views.mjs from scripts/metrics/registry.mjs. Do not edit by hand. -->', '# Pick n Edge · Metrics', '',
    'Every metric is defined once in `scripts/metrics/registry.mjs`. Ratios are `Σ numerator ÷ Σ denominator` over the games of the window (Season, last 3/5/10 team games), never an average of per-game ratios.', '',
    '**Naming.** `/100` = count × 100 ÷ possessions while on court: offense stats (PTS, AST, TOV, OREB, FD) per 100 team offensive possessions, defense stats (STL, BLK, DREB) per 100 team defensive possessions; REB/100 combines both phases (× 200 ÷ (offensive + defensive possessions)). `%` = part of a defined whole. No suffix = per game or per minute, as stated in the label. Team turnovers are "TOV/100", never "TOV%".', '',
    '**Components.** Player rows: `data/clean/player_games.csv`. Team rows: `team_games.csv`, with the opponent\'s figures as `o_<column>`. Derived components: ' + Object.entries(DERIVED).map(([k, t]) => `\`${k}\` = ${termText(t)}`).join('; ') + '.', '',
    ...section('Players', 'player'), ...section('Teams', 'team')].join('\n');
}

// ---- run ----
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const views = buildViews({ players: read('player_games.csv'), teams: read('team_games.csv'), dim: read('players.csv') });
  mkdirSync(out, { recursive: true });
  const files = [];
  const put = (name, data) => { writeFileSync(join(out, name), JSON.stringify(data)); files.push(name); };
  for (const [w, v] of Object.entries(views)) { put(`players-${w}.json`, v.players); put(`teams-${w}.json`, v.teams); }
  put('metrics.json', catalog());
  const teams = read('team_games.csv'), last = [...teams].sort(byGame).at(-1);
  writeFileSync(join(out, 'manifest.json'), JSON.stringify({ season: teams[0].season, games: new Set(teams.map(t => t.game)).size, lastGame: last.game, lastDate: last.date_utc, windows: Object.keys(WINDOWS), files }, null, 1) + '\n');
  mkdirSync(join(repo, 'docs'), { recursive: true });
  writeFileSync(join(repo, 'docs', 'METRICS.md'), docsMarkdown() + '\n');
  console.log(`views: ${Object.keys(views).length} windows, ${PLAYER_METRICS.length} player + ${TEAM_METRICS.length} team metrics -> ${out}`);
}
