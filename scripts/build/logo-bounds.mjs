// Visible bounding box of every team logo (transparent margins removed) -> assets/logo-bounds.js. Run `node scripts/build/logo-bounds.mjs` after adding or changing a logo.
// Needs sharp (dev only). The box is metadata of the logo file, not of any chart: the charts fit this box, not the whole picture, into the same square.
import sharp from 'sharp';
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../../site/assets/logos/', import.meta.url)), out = fileURLToPath(new URL('../../site/assets/logo-bounds.js', import.meta.url));
const ALPHA = 24;   // pixels fainter than this count as transparent
const rows = [];
for (const file of readdirSync(dir).filter(f => f.endsWith('.png')).sort()) {
  const { data, info } = await sharp(dir + file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3] > ALPHA) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  rows.push(`"${file.replace('.png', '')}": { "w": ${info.width}, "h": ${info.height}, "x": ${x0}, "y": ${y0}, "bw": ${x1 - x0 + 1}, "bh": ${y1 - y0 + 1} }`);
}
writeFileSync(out, `/* Visible bounding box of each team logo in pixels (picture size w x h, artwork box x, y, bw, bh), by catalogue id. Generated by scripts/build/logo-bounds.mjs; do not edit by hand. */\nexport const LOGO_BOUNDS = {\n${rows.join(',\n')}\n};\n`);
console.log(rows.join('\n'));
